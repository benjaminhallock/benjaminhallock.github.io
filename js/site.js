/* ==========================================================================
   site.js — profile rail + snapped post scroller
   Depends on js/content.js (generated by scripts/build-content.js).
   ========================================================================== */
(function () {
  'use strict'

  const data = window.SITE_CONTENT
  if (!data || !Array.isArray(data.items)) {
    console.error('site.js: window.SITE_CONTENT missing — run `npm run content`')
    return
  }

  const items = data.items
  const counts = data.counts || {}
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches

  const feed = document.getElementById('feed')
  const indexEl = document.getElementById('index')
  const tabsEl = document.getElementById('tabs')
  const counterEl = document.getElementById('counter')
  const bgEl = document.getElementById('bg')
  const rail = document.getElementById('rail')
  const railToggle = document.getElementById('rail-toggle')
  const railReveal = document.getElementById('rail-reveal')

  if (!feed || !indexEl) return

  /* ---------- helpers ---------------------------------------------------- */
  const pad = n => String(n).padStart(2, '0')
  const panelFor = new Map()

  const thumbFor = item => {
    if (item.type === 'photo') return item.src
    return item.cover || '/img/15.webp'
  }

  /* ---------- background crossfade --------------------------------------- */
  let bgFront = null
  function initBg() {
    if (!bgEl) return
    bgEl.innerHTML = ''
    for (let i = 0; i < 2; i++) {
      const d = document.createElement('div')
      d.className = 'slide'
      bgEl.appendChild(d)
    }
    bgFront = bgEl.children[0]
    bgFront.classList.add('is-active')
    bgFront.style.backgroundImage = `url('${thumbFor(items[0])}')`
  }

  function setBg(src) {
    if (!bgEl || !src) return
    const slides = bgEl.querySelectorAll('.slide')
    if (slides.length < 2) return
    const back = slides[0] === bgFront ? slides[1] : slides[0]
    back.style.backgroundImage = `url('${src}')`
    back.classList.add('is-active')
    bgFront.classList.remove('is-active')
    bgFront = back
  }

  /* ---------- rendering -------------------------------------------------- */
  function buildPanels() {
    const frag = document.createDocumentFragment()
    for (const item of items) {
      const panel = document.createElement('section')
      panel.className = 'panel'
      panel.id = `item-${item.id}`
      panel.setAttribute('aria-roledescription', 'post')
      panel.dataset.type = item.type
      panel.appendChild(renderCard(item))
      frag.appendChild(panel)
      panelFor.set(item.id, panel)
    }
    feed.appendChild(frag)
  }

  function renderCard(item) {
    if (item.type === 'photo') {
      const fig = document.createElement('figure')
      fig.className = 'card card--photo'
      const img = document.createElement('img')
      img.src = item.src
      img.alt = item.alt || ''
      img.loading = 'lazy'
      img.decoding = 'async'
      const cap = document.createElement('figcaption')
      cap.textContent = `Photography`
      fig.append(img, cap)
      return fig
    }

    const card = document.createElement('article')
    card.className = 'card'

    const head = document.createElement('div')
    head.className = 'card-head'
    head.innerHTML = `
      <img class="avatar" src="/img/bengi.webp" alt="" width="36" height="36" loading="lazy" />
      <div class="card-head-meta">
        <span class="card-head-name">Benjamin Hallock</span>
        <span class="card-head-sub">${item.type === 'post' ? formatDate(item.date) : item.year || 'Project'}</span>
      </div>
      <span class="card-kind">${item.type === 'post' ? 'Writing' : 'Project'}</span>
    `

    const body = document.createElement('div')
    body.className = 'card-body'

    const kicker = document.createElement('p')
    kicker.className = 'card-kicker'
    kicker.textContent = item.kicker || ''

    const title = document.createElement('h2')
    title.className = 'card-title'
    title.textContent = item.title

    body.append(kicker, title)

    if (item.type === 'post' && item.body) {
      const article = document.createElement('div')
      article.className = 'card-article blog-content'
      article.innerHTML = item.body
      body.appendChild(article)
    } else {
      const summary = document.createElement('p')
      summary.className = 'card-summary'
      summary.textContent = item.summary || ''
      body.appendChild(summary)
    }

    if (item.tags && item.tags.length) {
      const tags = document.createElement('ul')
      tags.className = 'card-tags'
      for (const t of item.tags) {
        const li = document.createElement('li')
        li.textContent = t
        tags.appendChild(li)
      }
      body.appendChild(tags)
    }

    if (item.href && item.type !== 'post') {
      const a = document.createElement('a')
      a.className = 'card-link'
      a.href = item.href
      a.innerHTML = `<span>${item.linkLabel || 'Read more'}</span>
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h14M13 6l6 6-6 6"/></svg>`
      body.appendChild(a)
    }

    card.append(head, body)

    if (item.images && item.images.length) {
      const media = document.createElement('div')
      media.className = 'card-media'
      for (const src of item.images.slice(0, 3)) {
        const img = document.createElement('img')
        img.src = src
        img.alt = ''
        img.loading = 'lazy'
        img.decoding = 'async'
        media.appendChild(img)
      }
      card.appendChild(media)
    }

    return card
  }

  /* ---------- state ------------------------------------------------------ */
  let visible = items.slice()
  let current = 0

  function renderIndex() {
    indexEl.innerHTML = ''
    const frag = document.createDocumentFragment()
    visible.forEach((item, i) => {
      const li = document.createElement('li')
      const btn = document.createElement('button')
      btn.type = 'button'
      btn.className = 'index-item'
      btn.dataset.id = item.id
      btn.innerHTML = `<span class="index-num">${pad(i + 1)}</span>
        <span class="index-label">${
          item.type === 'photo' ? `Photography ${pad(i + 1)}` : item.title
        }</span>`
      btn.addEventListener('click', () => {
        goTo(i, { hash: 'push' })
        if (window.matchMedia('(max-width: 720px)').matches) setRailHidden(true, false)
      })
      li.appendChild(btn)
      frag.appendChild(li)
    })
    indexEl.appendChild(frag)
    markIndexActive()
  }

  function markIndexActive() {
    const activeId = visible[current] && visible[current].id
    indexEl.querySelectorAll('.index-item').forEach(el => {
      const on = el.dataset.id === activeId
      el.setAttribute('aria-current', on ? 'true' : 'false')
      if (on) el.scrollIntoView({ block: 'nearest' })
    })
  }

  function updateCounter(item, position) {
    if (!counterEl) return
    counterEl.innerHTML = `<b>${pad(position + 1)}</b> <span aria-hidden="true">/</span> ${pad(
      visible.length,
    )}`
    counterEl.setAttribute('aria-label', `${item.title || 'Photo'}, item ${position + 1} of ${visible.length}`)
  }

  /* ---------- navigation ------------------------------------------------- */
  function setActive(i, hashMode) {
    if (!visible.length) return
    i = Math.max(0, Math.min(visible.length - 1, i))
    current = i
    const item = visible[i]
    markIndexActive()
    updateCounter(item, i)
    setBg(thumbFor(item))

    if (hashMode === 'push') history.pushState({ id: item.id }, '', `#${item.id}`)
    else if (hashMode === 'replace') history.replaceState({ id: item.id }, '', `#${item.id}`)
  }

  function goTo(i, opts) {
    opts = opts || {}
    if (!visible.length) return
    i = Math.max(0, Math.min(visible.length - 1, i))
    const panel = panelFor.get(visible[i].id)
    if (!panel) return

    setActive(i, opts.hash || false)

    const instant = opts.instant || reduced
    if (!instant) lockScrollSync()

    const top = panel.offsetTop
    feed.scrollTo({ top, behavior: instant ? 'instant' : 'smooth' })
  }

  function next() {
    goTo(current + 1, { hash: 'push' })
  }
  function prev() {
    goTo(current - 1, { hash: 'push' })
  }

  /* While a click/keyboard jump animates, the scroll handler must not
     re-activate the panels the animation passes through. */
  let scrollSyncLocked = false
  let scrollLockTimer = null
  function lockScrollSync() {
    scrollSyncLocked = true
    clearTimeout(scrollLockTimer)
    scrollLockTimer = setTimeout(unlockScrollSync, 900)
  }
  function unlockScrollSync() {
    scrollSyncLocked = false
    clearTimeout(scrollLockTimer)
  }

  /* keep the rail in sync while the user scrolls */
  let scrollTick = null
  function onScroll() {
    if (scrollSyncLocked || scrollTick) return
    scrollTick = requestAnimationFrame(() => {
      scrollTick = null
      if (!visible.length) return
      let best = 0
      let bestD = Infinity
      visible.forEach((item, i) => {
        const p = panelFor.get(item.id)
        if (!p) return
        const d = Math.abs(p.offsetTop - feed.scrollTop)
        if (d < bestD) {
          bestD = d
          best = i
        }
      })
      if (best !== current) setActive(best, 'replace')
    })
  }

  /* ---------- filters ---------------------------------------------------- */
  function matches(item, filter) {
    if (filter === 'all') return true
    if (filter === 'blog') return item.type === 'project' || item.type === 'post'
    if (filter === 'photos') return item.type === 'photo'
    return true
  }

  function applyFilter(filter) {
    visible = items.filter(item => matches(item, filter))

    panelFor.forEach((panel, id) => {
      panel.classList.toggle('is-hidden', !visible.some(v => v.id === id))
    })

    if (tabsEl) {
      tabsEl.querySelectorAll('.tab').forEach(t => {
        t.setAttribute('aria-selected', t.dataset.filter === filter ? 'true' : 'false')
      })
    }

    if (!visible.length) return
    unlockScrollSync()
    feed.scrollTo({ top: 0, behavior: 'instant' })
    current = 0
    renderIndex()
    setActive(0, 'replace')
  }

  /* ---------- rail collapse ---------------------------------------------- */
  const RAIL_KEY = 'bh.rail.hidden'
  function setRailHidden(hidden, persist) {
    document.body.classList.toggle('rail-hidden', hidden)
    if (rail) rail.setAttribute('aria-hidden', hidden ? 'true' : 'false')
    if (railToggle) railToggle.setAttribute('aria-expanded', hidden ? 'false' : 'true')
    if (railReveal) railReveal.setAttribute('aria-expanded', hidden ? 'false' : 'true')
    if (persist) {
      try {
        localStorage.setItem(RAIL_KEY, hidden ? '1' : '0')
      } catch (e) {}
    }
  }

  function toggleRail() {
    setRailHidden(!document.body.classList.contains('rail-hidden'), true)
  }

  /* ---------- input ------------------------------------------------------ */
  function bindInput() {
    if (railToggle) railToggle.addEventListener('click', toggleRail)
    if (railReveal) railReveal.addEventListener('click', toggleRail)

    const prevBtn = document.getElementById('prev-btn')
    const nextBtn = document.getElementById('next-btn')
    if (prevBtn) prevBtn.addEventListener('click', prev)
    if (nextBtn) nextBtn.addEventListener('click', next)

    if (tabsEl) {
      tabsEl.addEventListener('click', e => {
        const tab = e.target.closest('.tab')
        if (tab) applyFilter(tab.dataset.filter)
      })
    }

    feed.addEventListener('scroll', onScroll, { passive: true })
    feed.addEventListener('scrollend', unlockScrollSync, { passive: true })

    document.addEventListener('keydown', e => {
      const tag = (e.target.tagName || '').toLowerCase()
      if (tag === 'input' || tag === 'textarea' || e.metaKey || e.ctrlKey || e.altKey) return

      switch (e.key) {
        case 'ArrowDown':
        case 'ArrowRight':
        case 'j':
        case 'n':
          e.preventDefault()
          next()
          break
        case 'ArrowUp':
        case 'ArrowLeft':
        case 'k':
        case 'p':
          e.preventDefault()
          prev()
          break
        case 'Home':
          e.preventDefault()
          goTo(0, { hash: 'push' })
          break
        case 'End':
          e.preventDefault()
          goTo(visible.length - 1, { hash: 'push' })
          break
        case '[':
        case '\\':
          e.preventDefault()
          toggleRail()
          break
        default:
          if (/^[1-9]$/.test(e.key)) {
            const n = Number(e.key) - 1
            if (n < visible.length) goTo(n, { hash: 'push' })
          }
      }
    })

    window.addEventListener('popstate', () => {
      const id = location.hash.slice(1)
      const i = visible.findIndex(v => v.id === id)
      if (i >= 0) goTo(i, { hash: false })
    })
  }

  /* ---------- misc ------------------------------------------------------- */
  function formatDate(value) {
    if (!value) return ''
    const d = new Date(value)
    if (Number.isNaN(d.getTime())) return value
    return d.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' })
  }

  /* ---------- boot ------------------------------------------------------- */
  function boot() {
    initBg()
    buildPanels()
    renderIndex()

    let stored = null
    try {
      stored = localStorage.getItem(RAIL_KEY)
    } catch (e) {}
    const smallScreen = window.matchMedia('(max-width: 720px)').matches
    setRailHidden(stored === null ? smallScreen : stored === '1', false)

    const initialId = location.hash.slice(1)
    const initial = initialId ? visible.findIndex(v => v.id === initialId) : 0
    goTo(initial >= 0 ? initial : 0, { hash: false, instant: true })

    const statBlog = document.querySelector('[data-stat="blog"]')
    const statPhotos = document.querySelector('[data-stat="photos"]')
    if (statBlog) statBlog.textContent = (counts.projects || 0) + (counts.writing || 0)
    if (statPhotos) statPhotos.textContent = counts.photos || 0

    bindInput()
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', boot)
  } else {
    boot()
  }
})()
